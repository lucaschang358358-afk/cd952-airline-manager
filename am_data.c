static int isin_deg10(int deg10) {
    int neg = 0;
    if (deg10 < 0) { neg = 1; deg10 = -deg10; }
    deg10 %= 3600;
    if (deg10 > 1800) { deg10 = 3600 - deg10; neg = !neg; }
    if (deg10 > 900) deg10 = 1800 - deg10;
    int d0 = deg10 / 10, rem = deg10 % 10;
    int v0 = SIN90_10K[d0];
    int v1 = (d0 < 90) ? SIN90_10K[d0 + 1] : 10000;
    int v = v0 + ((v1 - v0) * rem) / 10;
    return neg ? -v : v;
}

static int icos_deg10(int deg10) { return isin_deg10(900 - abs(deg10)); }

int am_calc_distance_km(int ap1_idx, int ap2_idx) {
    if (ap1_idx == ap2_idx) return 0;
    const AirportInfo *a = am_airport_get(ap1_idx);
    const AirportInfo *b = am_airport_get(ap2_idx);

    int dlon = abs((int)a->lon10 - (int)b->lon10);
    if (dlon > 1800) dlon = 3600 - dlon;

    int64_t s1 = isin_deg10(a->lat10), s2 = isin_deg10(b->lat10);
    int64_t c1 = icos_deg10(a->lat10), c2 = icos_deg10(b->lat10);
    int64_t cd = icos_deg10(dlon);

    /* cos(theta) * 1000 = (s1*s2)/100000 + (c1*c2*cd)/1000000000 */
    int64_t term1 = (s1 * s2) / 100000LL;
    int64_t term2 = (((c1 * c2) / 10000LL) * cd) / 100000LL;
    int idx = (int)(term1 + term2) + 1000;
    if (idx < 0) idx = 0;
    if (idx > 2000) idx = 2000;
    int km = (int)ACOS_KM_TAB[idx];
    return (km < 80) ? 80 : km;
}

/* 計算兩座機場之間的真實雙邊每日需求 (結合雙方市場規模與航程特性!) */
void am_calc_route_demand(int ap1_idx, int ap2_idx, int *out_y, int *out_j, int *out_f, int *out_cargo) {
    const AirportInfo *a = am_airport_get(ap1_idx);
    const AirportInfo *b = am_airport_get(ap2_idx);
    int dist = am_calc_distance_km(ap1_idx, ap2_idx);

    /* 結合兩端機場的真實市場規模 (幾何平均近似) */
    int dy = ((int)a->dem_y + (int)b->dem_y) / 2;
    int dj = ((int)a->dem_j + (int)b->dem_j) / 2;
    int df = ((int)a->dem_f + (int)b->dem_f) / 2;

    /* 同國/區域短程經濟艙更旺；洲際長程商務/頭等艙比例更高 */
    int intl_bonus = (strcmp(a->country, b->country) != 0) ? 112 : 100;
    int dist_y = (dist < 2500) ? 115 : ((dist > 9000) ? 85 : 100);
    int dist_jf = (dist > 4500) ? 120 : ((dist < 1200) ? 75 : 100);

    int y = (dy * intl_bonus * dist_y) / 10000;
    int j = (dj * intl_bonus * dist_jf) / 10000;
    int f = (df * intl_bonus * dist_jf) / 10000;
    int cg = ((y + j * 2) * 18) / 100;
    if (y < 120) y = 120;
    if (j < 30)  j = 30;
    if (f < 8)   f = 8;
    if (cg < 40) cg = 40;

    if (out_y) *out_y = y;
    if (out_j) *out_j = j;
    if (out_f) *out_f = f;
    if (out_cargo) *out_cargo = cg;
}

