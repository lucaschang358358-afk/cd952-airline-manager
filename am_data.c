const char *am_country_code(int c_idx) {
    if (c_idx < 0 || c_idx >= g_country_count) c_idx = 0;
    return g_countries[c_idx];
}
const char *am_country_name_zh(const char *code) {
    if (!code) return "未知";
    int n = (int)(sizeof(COUNTRY_ZH) / sizeof(COUNTRY_ZH[0]));
    for (int i = 0; i < n; i++) if (strcmp(COUNTRY_ZH[i].code, code) == 0) return COUNTRY_ZH[i].zh;
    return code;
}
int am_airports_in_country(const char *code, int *out_idxs, int max_n) {
    int cnt = 0;
    if (!code) return 0;
    for (int i = 0; i < g_airport_count && cnt < max_n; i++) {
        if (strcmp(g_airports[i].country, code) == 0) out_idxs[cnt++] = i;
    }
    return cnt;
}

void am_data_init(const char *extra_csv_path) {
    int n = (int)(sizeof(BUILTIN_AIRPORTS) / sizeof(BUILTIN_AIRPORTS[0]));
    if (n > AM_MAX_AIRPORTS) n = AM_MAX_AIRPORTS;
    memcpy(g_airports, BUILTIN_AIRPORTS, (size_t)n * sizeof(AirportInfo));
    g_airport_count = n;
    load_extra_csv(extra_csv_path);
    rebuild_country_index();
}

