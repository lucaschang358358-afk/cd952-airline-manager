static char g_countries[AM_MAX_COUNTRIES][4];
static int  g_country_count = 0;

static void rebuild_country_index(void) {
    g_country_count = 0;
    for (int i = 0; i < g_airport_count; i++) {
        const char *cc = g_airports[i].country;
        int found = 0;
        for (int c = 0; c < g_country_count; c++) {
            if (strcmp(g_countries[c], cc) == 0) { found = 1; break; }
        }
        if (!found && g_country_count < AM_MAX_COUNTRIES) {
            snprintf(g_countries[g_country_count++], 4, "%s", cc);
        }
    }
}

