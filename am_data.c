static AirportInfo g_airports[AM_MAX_AIRPORTS];
static int g_airport_count = 0;

static const char *MFG_NAMES[6] = {
    "Airbus", "Boeing", "Embraer", "Regional", "Special", "Cargo"
};

const char *am_mfg_name(int mfg) {
    if (mfg < 0 || mfg >= 6) return "All";
    return MFG_NAMES[mfg];
}

int am_airport_count(void) { return g_airport_count; }
const AirportInfo *am_airport_get(int idx) {
    if (idx < 0 || idx >= g_airport_count) idx = 0;
    return &g_airports[idx];
}

int am_airport_find_iata(const char *iata) {
    if (!iata || !iata[0]) return -1;
    for (int i = 0; i < g_airport_count; i++) {
        if (g_airports[i].iata[0] == toupper((unsigned char)iata[0]) &&
            g_airports[i].iata[1] == toupper((unsigned char)iata[1]) &&
            g_airports[i].iata[2] == toupper((unsigned char)iata[2])) return i;
    }
    return -1;
}

int am_aircraft_count(void) { return (int)(sizeof(BUILTIN_AIRCRAFT) / sizeof(BUILTIN_AIRCRAFT[0])); }
const AircraftModel *am_aircraft_get(int idx) {
    int n = am_aircraft_count();
    if (idx < 0 || idx >= n) idx = 0;
    return &BUILTIN_AIRCRAFT[idx];
}

/* 外部 airports.csv 擴充載入器 (支援 OurAirports 或自訂 IATA,Name,Country,Lat,Lon,RunwayFt 格式!) */
static void load_extra_csv(const char *csv_path) {
    if (!csv_path || !csv_path[0]) return;
    FILE *f = fopen(csv_path, "rb");
    if (!f) return;
    char line[256];
    while (fgets(line, sizeof(line), f) && g_airport_count < AM_MAX_AIRPORTS) {
        if (line[0] == '#' || line[0] == '\n' || line[0] == '\r') continue;
        char iata[8] = {0}, name[32] = {0}, cc[8] = {0};
        double lat = 0, lon = 0; int rwy = 7500;
        if (sscanf(line, "%3[^,],%27[^,],%2[^,],%lf,%lf,%d", iata, name, cc, &lat, &lon, &rwy) >= 5) {
            if (!isalpha((unsigned char)iata[0]) || !isalpha((unsigned char)iata[1]) || !isalpha((unsigned char)iata[2])) continue;
            if (am_airport_find_iata(iata) >= 0) continue;
            AirportInfo *ap = &g_airports[g_airport_count++];
            memset(ap, 0, sizeof(*ap));
            for (int k = 0; k < 3; k++) ap->iata[k] = (char)toupper((unsigned char)iata[k]);
            snprintf(ap->name, sizeof(ap->name), "%s", name);
            snprintf(ap->country, sizeof(ap->country), "%s", cc);
            ap->lat10 = (int16_t)(lat * 10.0);
            ap->lon10 = (int16_t)(lon * 10.0);
            ap->runway_ft = (uint16_t)(rwy > 2000 ? rwy : 6500);
            ap->market_pct = 72;
            ap->dem_y = 650; ap->dem_j = 190; ap->dem_f = 55;
        }
    }
    fclose(f);
}


