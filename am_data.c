static uint32_t isqrt_u64(uint64_t n) {
    if (n == 0) return 0;
    uint64_t x = n, y = (x + 1) >> 1;
    while (y < x) { x = y; y = (x + n / x) >> 1; }
    return (uint32_t)x;
}

int am_calc_distance_km(int ap1_idx, int ap2_idx) {
    if (ap1_idx == ap2_idx) return 0;
    const AirportInfo *a = am_airport_get(ap1_idx);
    const AirportInfo *b = am_airport_get(ap2_idx);

    int dlat = abs((int)a->lat10 - (int)b->lat10); /* 0.1 deg */
    int dlon = abs((int)a->lon10 - (int)b->lon10);
    if (dlon > 1800) dlon = 3600 - dlon;

    int avg_lat = abs(((int)a->lat10 + (int)b->lat10) / 20);
    if (avg_lat > 90) avg_lat = 90;

    /* 每度緯度 = 111.2 km -> 每 0.1 度 = 11.12 km */
    uint64_t dy = ((uint64_t)dlat * 1112u) / 100u;
    uint64_t dx = ((uint64_t)dlon * 1112u * (uint64_t)COS90[avg_lat]) / 100000u;
    int km = (int)isqrt_u64(dx * dx + dy * dy);
    if (km < 80) km = 80;
    if (km > 19800) km = 19800;
    return km;
}

